#!/usr/bin/env python3
"""Render every HD dial (screen size x style preset x background) with tools/render_hd.py and
write them, with their drawables.xml, into the resource folders:

  hd/<size>/drawables/                 one folder per screen size (MIP below 360 px, AMOLED from
                                       360 px); monkey.jungle adds it to the resource path of the
                                       Connect IQ 4+ watches only (older watches use the vector dial)

All images are stored in full colour (JPEG, quality 90). For AMOLED sizes they are packed as
JPEG on the device (packingFormat="jpg"). For MIP sizes the Connect IQ compiler converts them
to the exact palette declared by each device file (64 or more colours, Floyd-Steinberg
dithering) with its default packing, so no colour depth is assumed here.
A Friday dial per size (tools/render_friday.py, id DialFri) is added.
Usage: python3 tools/build_hd.py [--friday] [size ...]   (default: all sizes; 4 worker processes;
--friday renders only the Friday dials)
"""
import multiprocessing as mp
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import render_hd  # noqa: E402
import render_friday  # noqa: E402

ROOT = render_hd.ROOT
SIZES = [218, 240, 260, 280, 360, 390, 416, 454, 466]
NSTYLES = len(render_hd.STYLES)
BGS = render_hd.BACKGROUNDS


def folder(size):
    return os.path.join(ROOT, "hd", str(size), "drawables")


def exact(size, s):
    """High-contrast styles on MIP sizes: palette-exact PNG, no dithering (render_hd.flat_finish)."""
    return size < render_hd.AMOLED_FROM and render_hd.is_flat(s)


def fname(size, s, b):
    return "dial_%d_%d.%s" % (s, b, "png" if exact(size, s) else "jpg")


def num_name(s, d, q):
    return "num_%d_%d_%d.png" % (s, d, q)


def sprite_job(args):
    """Numeral bitmaps (12 / 3 / 6 / 9, Arabic and Indian digits) of one style."""
    size, s = args
    total = 0
    for (d, q), img in render_hd.numeral_sprites(size, s).items():
        if exact(size, s):
            img = render_hd.flat_finish(img)
        path = os.path.join(folder(size), num_name(s, d, q))
        img.save(path, optimize=True)
        total += os.path.getsize(path)
    return os.path.join(folder(size), num_name(s, 0, 0)), total


FRIDAY = "dial_fri.jpg"     # Friday dial (tools/render_friday.py), id DialFri


def friday_job(size):
    img = render_friday.render(size)
    if size < render_hd.AMOLED_FROM:
        img = render_hd.mip_grade(img)
    path = os.path.join(folder(size), FRIDAY)
    img.convert("RGB").save(path, "JPEG", quality=90, optimize=True, subsampling=0)
    return path, os.path.getsize(path)


def job(args):
    if len(args) == 1:
        return friday_job(args[0])
    if len(args) == 2:
        return sprite_job(args)
    size, s, b = args
    img = render_hd.render(size, s, BGS[b])
    path = os.path.join(folder(size), fname(size, s, b))
    if exact(size, s):
        render_hd.flat_finish(img).convert("RGB").save(path, optimize=True)
        return path, os.path.getsize(path)
    if size < render_hd.AMOLED_FROM:
        img = render_hd.mip_grade(img)
    img.convert("RGB").save(path, "JPEG", quality=90, optimize=True, subsampling=0)
    return path, os.path.getsize(path)


def write_xml(size):
    lines = ["<drawables>"]
    lines.append("    <!-- HD static dial art, generated by tools/build_hd.py: DialSB = style S, background B -->")
    amoled = size >= render_hd.AMOLED_FROM
    for s in range(NSTYLES):
        for b in range(len(BGS)):
            if amoled:
                lines.append('    <bitmap id="Dial%d%d" filename="%s" packingFormat="jpg" />' % (s, b, fname(size, s, b)))
            elif exact(size, s):
                lines.append('    <bitmap id="Dial%d%d" filename="%s" dithering="none" />' % (s, b, fname(size, s, b)))
            else:
                lines.append('    <bitmap id="Dial%d%d" filename="%s" dithering="floyd_steinberg" />'
                             % (s, b, fname(size, s, b)))
    if amoled:
        lines.append('    <bitmap id="DialFri" filename="%s" packingFormat="jpg" />' % FRIDAY)
    else:
        lines.append('    <bitmap id="DialFri" filename="%s" dithering="floyd_steinberg" />' % FRIDAY)
    lines.append("    <!-- numerals 12 / 3 / 6 / 9: NumSDQ = style S, digits D (0 Arabic, 1 Indian), position Q -->")
    for s in range(NSTYLES):
        for d in range(2):
            for q in range(4):
                extra = '' if amoled else (' dithering="none"' if exact(size, s) else ' dithering="floyd_steinberg"')
                lines.append('    <bitmap id="Num%d%d%d" filename="%s"%s />' % (s, d, q, num_name(s, d, q), extra))
    lines.append("</drawables>")
    with open(os.path.join(folder(size), "drawables.xml"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    """build_hd.py [--friday] [size ...]: --friday renders only the Friday dials."""
    only_friday = "--friday" in sys.argv
    sizes = [int(a) for a in sys.argv[1:] if not a.startswith("--")] or SIZES
    for size in sizes:
        os.makedirs(folder(size), exist_ok=True)
        if not only_friday:
            for f in os.listdir(folder(size)):
                if f.startswith(("dial_", "num_")):
                    os.remove(os.path.join(folder(size), f))
        write_xml(size)
    jobs = [] if only_friday else [(size, s, b) for size in sizes for s in range(NSTYLES) for b in range(len(BGS))]
    jobs += [] if only_friday else [(size, s) for size in sizes for s in range(NSTYLES)]
    jobs += [(size,) for size in sizes]
    total = {}
    with mp.Pool(4) as pool:
        for path, n in pool.imap_unordered(job, jobs):
            size = int(os.path.relpath(path, ROOT).split(os.sep)[1])
            total[size] = total.get(size, 0) + n
            print("%6d KB  %s" % (n // 1024, os.path.relpath(path, ROOT)), flush=True)
    for size in sorted(total):
        print("%d px: %d KB written" % (size, total[size] // 1024))


if __name__ == "__main__":
    main()
