#!/usr/bin/env python3
"""Version of Muslim Watch: increments it for each delivery and propagates it.

The application version lives in manifest.xml (<iq:application version="X.Y.Z">). This script
  * increments the last number (1.0.8 -> 1.0.9), or sets the version given with --set X.Y.Z;
  * writes source/Version.mc, read by the on-watch About menu (SettingsMenu.about);
  * adds a "## X.Y.Z" section at the top of CHANGELOG.md if it is not there yet.
Run it once per delivery, before the commit:  python3 tools/bump_version.py
tools/check_project.py fails if manifest.xml and source/Version.mc disagree.
"""
import datetime
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "manifest.xml")
VERSION_MC = os.path.join(ROOT, "source", "Version.mc")
CHANGELOG = os.path.join(ROOT, "CHANGELOG.md")
PATTERN = re.compile(r'(<iq:application[^>]*\sversion=")(\d+)\.(\d+)\.(\d+)(")')


def current():
    m = PATTERN.search(open(MANIFEST).read())
    if not m:
        raise SystemExit("manifest.xml: no version attribute on <iq:application>")
    return "%s.%s.%s" % (m.group(2), m.group(3), m.group(4))


def write(version):
    major, minor, patch = version.split(".")
    s = open(MANIFEST).read()
    s = PATTERN.sub(lambda m: "%s%s.%s.%s%s" % (m.group(1), major, minor, patch, m.group(5)), s, count=1)
    open(MANIFEST, "w").write(s)
    open(VERSION_MC, "w").write(
        "import Toybox.Lang;\n\n"
        "// Generated by tools/bump_version.py from manifest.xml: do not edit by hand.\n"
        "module AppVersion {\n"
        "    const VERSION = \"%s\";\n"
        "}\n" % version)
    log = open(CHANGELOG).read()
    if not re.search(r"^## %s\b" % re.escape(version), log, re.M):
        i = log.find("\n## ")
        i = len(log) if i < 0 else i + 1
        entry = "## %s (%s)\n\n" % (version, datetime.date.today().isoformat())
        open(CHANGELOG, "w").write(log[:i] + entry + log[i:])


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--set":
        version = sys.argv[2]
        if not re.fullmatch(r"\d+\.\d+\.\d+", version):
            raise SystemExit("version must look like 1.0.8")
    elif len(sys.argv) == 1:
        major, minor, patch = current().split(".")
        version = "%s.%s.%d" % (major, minor, int(patch) + 1)
    else:
        raise SystemExit(__doc__)
    write(version)
    print(version)


if __name__ == "__main__":
    main()
